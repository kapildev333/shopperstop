// Usage: npm run gen:tokens --workspace packages/ui
// Writes src/tokens.ts from src/tokens.css. generateTokens(css) is pure; the file is written only when run directly.
// Simplification: regex over `--name: value;` pairs, as check-figma-tokens.mjs does, not a CSS parser.
// Ceiling: a comment inside a block that looks like a declaration is read as a token.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const cssPath = join(here, '..', 'src', 'tokens.css')
const outPath = join(here, '..', 'src', 'tokens.ts')

// Spec 1 section 8.3 and 8.5 values that tokens.css does not declare (Tailwind defaults or utilities on the web side).
// Ceiling: if Spec 1 changes them, edit here; move them into tokens.css when the web side needs them as utilities.
const FIXED = {
  radius: { pill: 9999 }, // rounded-full
  spacing: { unit: 4, gutter: 16, gridGap: 12 }, // phone gutter only; desktop 24 omitted (D38)
  motion: { sheetDuration: 200 }, // duration-200 on Sheet
}

const TYPE_NAMES = ['display', 'h1', 'h2', 'h3', 'body', 'small', 'button']
const SHADOW = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const hex2 = (n) => Number(n).toString(16).padStart(2, '0').toUpperCase()

function declarations(block) {
  return new Map([...block.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]))
}

export function generateTokens(css) {
  const root = /:root\s*\{([^}]*)\}/.exec(css)
  const theme = /@theme\s*\{([^}]*)\}/.exec(css)
  const rootVars = root ? declarations(root[1]) : new Map()
  const themeVars = theme ? declarations(theme[1]) : new Map()

  const get = (name) => {
    const value = themeVars.get(name) ?? rootVars.get(name)
    if (value === undefined) throw new Error(`tokens.css has no --${name}`)
    return value
  }
  const px = (name) => parseFloat(get(name))

  const colors = Object.fromEntries([...rootVars].map(([name, value]) => [camel(name), value]))

  const radius = { control: px('radius-control'), card: px('radius-card'), ...FIXED.radius }
  const spacing = { ...FIXED.spacing }
  const type = Object.fromEntries(
    TYPE_NAMES.map((n) => [
      n,
      {
        size: px(`text-${n}`),
        lineHeight: px(`text-${n}--line-height`),
        weight: parseFloat(get(`text-${n}--font-weight`)),
      },
    ]),
  )
  const motion = {
    duration: px('default-transition-duration'),
    sheetDuration: FIXED.motion.sheetDuration,
    easing: get('default-transition-timing-function'),
  }

  const shadow = (name) => {
    const value = get(name)
    const m = SHADOW.exec(value)
    if (!m) throw new Error(`unparsed shadow: ${value}`)
    const [, offsetX, offsetY, blur, r, g, b, alpha] = m
    return {
      boxShadow: value,
      offsetX: Number(offsetX),
      offsetY: Number(offsetY),
      blur: Number(blur),
      color: `#${hex2(r)}${hex2(g)}${hex2(b)}`,
      opacity: Number(alpha),
    }
  }
  const shadows = { card: shadow('shadow-card'), sheet: shadow('shadow-sheet') }

  const groups = { colors, radius, spacing, type, motion, shadows }
  const body = Object.entries(groups)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const\n`)
    .join('\n')
  return `// Generated by scripts/gen-tokens.mjs from tokens.css. Do not edit; run npm run gen:tokens.\n\n${body}`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(outPath, generateTokens(readFileSync(cssPath, 'utf8')))
}
